def _rows_for_block(start: int) -> tuple[np.ndarray, np.ndarray]:
    all_rows = np.arange(start, start + 96, dtype=np.int64)
    dmrs_rows = np.arange(start + 1, start + 96, 4, dtype=np.int64)
    mask = np.ones_like(all_rows, dtype=bool)
    mask[(dmrs_rows - start)] = False
    channel_rows = all_rows[mask]
    return channel_rows, dmrs_rows


def channel_linear_indices() -> np.ndarray:
    rows: list[np.ndarray] = []
    for start in (97, 313):
        channel_rows, _ = _rows_for_block(start)
        rows.append(channel_rows)
    base_rows = np.concatenate(rows)
    return np.concatenate([base_rows + (symbol_idx * GRID_ROWS) for symbol_idx in range(3)]).astype(np.int64)


def dmrs_linear_indices() -> np.ndarray:
    rows: list[np.ndarray] = []
    for start in (97, 313):
        _, dmrs_rows = _rows_for_block(start)
        rows.append(dmrs_rows)
    base_rows = np.concatenate(rows)
    return np.concatenate([base_rows + (symbol_idx * GRID_ROWS) for symbol_idx in range(3)]).astype(np.int64)


def channel_symbols() -> np.ndarray:
    return (QPSK_MAGNITUDE * (CHANNEL_REAL_SIGNS + 1j * CHANNEL_IMAG_SIGNS)).astype(np.complex128)


def dmrs_symbols() -> np.ndarray:
    return (QPSK_MAGNITUDE * (DMRS_REAL_SIGNS + 1j * DMRS_IMAG_SIGNS)).astype(np.complex128)


def symbol_phase_sequence(center_freq_hz: float) -> np.ndarray:
    offsets = np.cumsum(SYMBOL_LENGTHS, dtype=np.float64) - float(NFFT)
    return (-2.0 * np.pi * float(center_freq_hz) * offsets / float(SYMBOL_SAMPLE_RATE_HZ)).astype(np.float64)
